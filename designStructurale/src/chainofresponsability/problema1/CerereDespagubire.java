package chainofresponsability.problema1;

public class CerereDespagubire {
    private String nume;
    private double suma;

    public CerereDespagubire(String nume, double suma) {
        this.nume = nume;
        this.suma = suma;
    }

    public String getNume() {
        return nume;
    }

    public double getSuma() {
        return suma;
    }
}
